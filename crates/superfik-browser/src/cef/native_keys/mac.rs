//! What macOS calls a key. CEF rebuilds each key event as an `NSEvent` from
//! its `native_key_code` and character, ignoring the Windows code, so
//! Backspace, the arrows and Delete edit only when they carry the Mac's
//! own key code and the character AppKit gives them.

pub fn native_code(windows: i32) -> i32 {
    match windows {
        0x08 => 0x33,
        0x09 => 0x30,
        0x0D => 0x24,
        0x10 => 0x38,
        0x11 => 0x3B,
        0x12 => 0x3A,
        0x1B => 0x35,
        0x20 => 0x31,
        0x21 => 0x74,
        0x22 => 0x79,
        0x23 => 0x77,
        0x24 => 0x73,
        0x25 => 0x7B,
        0x26 => 0x7E,
        0x27 => 0x7C,
        0x28 => 0x7D,
        0x2E => 0x75,
        0x30..=0x39 => DIGITS[(windows - 0x30) as usize],
        0x41..=0x5A => LETTERS[(windows - 0x41) as usize],
        0x5B => 0x37,
        0x5C => 0x36,
        0x70..=0x7B => FUNCTIONS[(windows - 0x70) as usize],
        0xBA => 0x29,
        0xBB => 0x18,
        0xBC => 0x2B,
        0xBD => 0x1B,
        0xBE => 0x2F,
        0xBF => 0x2C,
        0xC0 => 0x32,
        0xDB => 0x21,
        0xDC => 0x2A,
        0xDD => 0x1E,
        0xDE => 0x27,
        _ => 0xFF,
    }
}

pub fn function_char(windows: i32) -> Option<char> {
    let code = match windows {
        0x08 => 0x7F,
        0x09 => 0x09,
        0x0D => 0x0D,
        0x1B => 0x1B,
        0x21 => 0xF72C,
        0x22 => 0xF72D,
        0x23 => 0xF72B,
        0x24 => 0xF729,
        0x25 => 0xF702,
        0x26 => 0xF700,
        0x27 => 0xF703,
        0x28 => 0xF701,
        0x2E => 0xF728,
        0x70..=0x7B => 0xF704 + (windows - 0x70) as u32,
        _ => return None,
    };
    char::from_u32(code)
}

const LETTERS: [i32; 26] = [
    0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E, 0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01,
    0x11, 0x20, 0x09, 0x0D, 0x07, 0x10, 0x06,
];
const DIGITS: [i32; 10] = [0x1D, 0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19];
const FUNCTIONS: [i32; 12] = [0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn editing_keys_carry_the_macs_codes_and_characters() {
        assert_eq!((native_code(0x08), function_char(0x08)), (0x33, Some('\u{7F}')), "Backspace");
        assert_eq!((native_code(0x2E), function_char(0x2E)), (0x75, Some('\u{F728}')), "Delete");
        assert_eq!((native_code(0x25), function_char(0x25)), (0x7B, Some('\u{F702}')), "Left");
        assert_eq!(native_code(0x41), 0x00, "A");
        assert_eq!(native_code(0x5A), 0x06, "Z");
        assert_eq!(native_code(0x30), 0x1D, "0");
        assert_eq!(function_char(0x41), None, "letters type their own text");
    }
}
