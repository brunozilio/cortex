pub(crate) fn plural(n: usize, one: &str, many: &str) -> String {
    if n == 1 { format!("{n} {one}") } else { format!("{n} {many}") }
}

pub(crate) fn size(bytes: u64, point: char) -> String {
    const MB: u64 = 1_000_000;
    const GB: u64 = 1_000_000_000;
    if bytes < GB {
        return format!("{} MB", bytes / MB);
    }
    let tenths = bytes / (GB / 10);
    format!("{}{point}{} GB", tenths / 10, tenths % 10)
}

pub(crate) fn percent(done: u64, total: u64) -> u64 {
    (done.saturating_mul(100) / total.max(1)).min(100)
}
