pub struct Reader {
    pub program: &'static [&'static str],
    pub flags: &'static [&'static str],
    pub clustered: bool,
    pub operands: bool,
}

const fn reader(program: &'static [&'static str], flags: &'static [&'static str]) -> Reader {
    Reader { program, flags, clustered: true, operands: true }
}

const fn listing(program: &'static [&'static str], flags: &'static [&'static str]) -> Reader {
    Reader { program, flags, clustered: true, operands: false }
}

const fn spelled_out(program: &'static [&'static str], flags: &'static [&'static str]) -> Reader {
    Reader { program, flags, clustered: false, operands: true }
}

