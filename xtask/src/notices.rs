//! `cargo run -p xtask -- notices <out>`: writes the third-party notices
//! the app ships with (Superfik is Apache-2.0; the components of other
//! authors keep their licences). The bundle scripts write it into the app;
//! it is not kept in the repository. Assets are listed by hand; the Rust
//! crates come from `cargo metadata`, grouped by their licence expression.

use std::collections::BTreeMap;
use std::path::Path;
use std::process::Command;

type Crate = (String, String, Option<String>);

fn ours(name: &str) -> bool {
    name.starts_with("superfik-") || name == "xtask"
}

