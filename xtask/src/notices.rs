pub fn render(crates: &[Crate]) -> String {
    let mut groups: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for (name, version, licence) in crates.iter().filter(|(name, ..)| !ours(name)) {
        let licence = licence.as_deref().unwrap_or("See the crate's own licence file");
        groups.entry(licence).or_default().push(format!("{name}@{version}"));
    }
    let mut out = String::from(ASSETS);
    for (licence, mut entries) in groups {
        entries.sort();
        entries.dedup();
        out.push_str(&format!("\n### {licence} ({})\n\n{}\n", entries.len(), entries.join(", ")));
    }
    out
}

fn crates(root: &Path) -> Result<Vec<Crate>, Box<dyn std::error::Error>> {
    let output =
        Command::new("cargo").args(["metadata", "--format-version", "1", "--locked"]).current_dir(root).output()?;
    if !output.status.success() {
        return Err(format!("cargo metadata failed: {}", String::from_utf8_lossy(&output.stderr)).into());
    }
    let metadata: serde_json::Value = serde_json::from_slice(&output.stdout)?;
    let packages = metadata["packages"].as_array().ok_or("cargo metadata has no packages")?;
    Ok(packages
        .iter()
        .map(|package| {
            let text = |key: &str| package[key].as_str().unwrap_or_default().to_owned();
            (text("name"), text("version"), package["license"].as_str().map(str::to_owned))
        })
        .collect())
}

pub fn run(root: &Path, out: &Path) -> Result<(), Box<dyn std::error::Error>> {
    std::fs::write(out, render(&crates(root)?))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn krate(name: &str, version: &str, licence: Option<&str>) -> Crate {
        (name.into(), version.into(), licence.map(str::to_owned))
    }

    #[test]
    fn crates_are_grouped_by_licence_and_ours_are_left_out() {
        let notices = render(&[
            krate("tokio", "1.0.0", Some("MIT")),
            krate("superfik-app", "0.0.0", Some("Apache-2.0")),
            krate("serde", "1.0.0", Some("MIT")),
            krate("xtask", "0.1.0", Some("Apache-2.0")),
            krate("bytemuck", "1.25.2", Some("Zlib OR Apache-2.0 OR MIT")),
        ]);
        assert!(notices.starts_with("# Third-party notices"));
        assert!(notices.contains("### MIT (2)\n\nserde@1.0.0, tokio@1.0.0\n"));
        assert!(notices.contains("### Zlib OR Apache-2.0 OR MIT (1)\n\nbytemuck@1.25.2\n"));
        assert!(!notices.contains("superfik-app"));
        assert!(!notices.contains("xtask@"));
    }

    #[test]
    fn a_crate_without_a_licence_expression_is_still_listed() {
        let notices = render(&[krate("ring", "0.17.14", None)]);
        assert!(notices.contains("### See the crate's own licence file (1)\n\nring@0.17.14\n"));
    }
}
